import { COLOR_COUNT } from '../src/core/palette';
import { Rng } from '../src/core/rng';
import { prepare } from '../src/designer/analyze';
import { Puzzle, analyzeGraph, samplePlays, sandFor } from '../src/designer/fast';
import { blankLevel } from '../src/designer/model';
import { newGame } from '../src/designer/solver';
const a = Number(process.argv[2] ?? 8);
const rng = new Rng(5);
const def0 = blankLevel(90, 'p', a);
const g0 = newGame(prepare(def0, 4), 1);
const colors: number[] = [];
for (let c = 0; c < COLOR_COUNT; c++) if (g0.sand.counts[c] > 0) colors.push(c);
const list = [...colors]; while (list.length < 14) list.push(colors[rng.int(colors.length)]);
const cells: [number, number][] = []; for (let r = 0; r < 4; r++) for (let c = 0; c < 5; c++) cells.push([r, c]);
const def = { ...def0, buckets: def0.buckets.map((r) => r.slice()) };
rng.shuffle(cells.slice()).slice(0, list.length).forEach(([r, c], i) => (def.buckets[r][c] = list[i].toString(36)));
const pr = prepare(def, 4);
const t0 = performance.now();
const p = new Puzzle(pr, sandFor(pr.art, 4));
const t1 = performance.now();
const rep = analyzeGraph(p, { maxNodes: 500, maxMs: 1500 });
const t2 = performance.now();
samplePlays(p, 120, 3);
const t3 = performance.now();
console.log(`puzzle ${(t1 - t0).toFixed(1)}ms  graph(500) ${(t2 - t1).toFixed(0)}ms nodes ${rep.nodes}  samples(120) ${(t3 - t2).toFixed(0)}ms`);
