// Chrome có cửa sổ: thêm màn mới, chọn tranh + độ khó, bấm Gen, rồi Tự giải.
import puppeteer from 'puppeteer-core';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const tag = process.argv[2] ?? 'hard';
const artIdx = process.argv[3] ?? '3';
const url = pathToFileURL(path.resolve('dist-designer/designer.html')).href;
const browser = await puppeteer.launch({ executablePath: 'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe', headless: false, defaultViewport: { width: 1500, height: 1000 } });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(url);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector('.lv');
await page.click('#bAdd');
await page.select('#artSel', artIdx);
await page.click(`.seg.${tag}`);
await page.click('#bGen');
const t0 = Date.now();
await page.waitForFunction(() => !document.querySelector('#bGen').textContent.includes('Dừng'), { timeout: 240000 });
console.log(`gen xong sau ${Math.round((Date.now() - t0) / 1000)}s`);
await new Promise((r) => setTimeout(r, 1500));
console.log((await page.$eval('#result', (e) => e.innerText)).split('\n').slice(0, 8).join('\n'));
console.log('board:\n' + (await page.$$eval('.cell', (cs) => cs.map((c) => (c.classList.contains('void') ? ' .' : c.classList.contains('wall') ? ' #' : c.querySelector('.bucket') ? ' B' : ' _')).join('')))); 
await page.screenshot({ path: `qa/results/designer-gen-${tag}.png` });
await page.click('#bAuto');
await page.waitForFunction(() => /THẮNG|KẸT/.test(document.querySelector('#result').innerText) && document.querySelector('#modeTag').innerText.includes('TỰ GIẢI'), { timeout: 120000 });
await page.waitForFunction(() => document.querySelectorAll('.case').length >= 1 && /THẮNG/.test(document.querySelector('#result').innerText), { timeout: 150000 });
console.log((await page.$eval('#result', (e) => e.innerText)).split('\n').join(' | '));
console.log('errors:', JSON.stringify(errors));
await browser.close();
